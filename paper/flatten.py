"""Write the whole paper as one LaTeX file, fct_paper.tex: every \\input of main.tex inlined (sections,
tables, the overview diagram) and the bibliography embedded from the BibTeX output (.bbl), so it builds
with pdflatex alone. It still needs IEEEtran.cls and the image files under figures/.

The sources in this folder stay the ones to edit: tables and figures are regenerated by their scripts,
and fct_paper.tex is regenerated from them.

Usage: python flatten.py [BBL]      # BBL: main.bbl from a full build (default: next to main.tex)
Build: pdflatex fct_paper.tex       # twice, for the cross-references
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
BBL = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, 'main.bbl')
INPUT = re.compile(r'^(\s*)\\input\{([^}]+)\}\s*$')


def expand(path, depth=0):
    assert depth < 5, path
    out = []
    for line in open(path, encoding='utf-8'):
        m = INPUT.match(line)
        if m:
            name = m.group(2) if m.group(2).endswith('.tex') else m.group(2) + '.tex'
            out.append('%% ---- %s ----\n' % name)
            for inner in expand(os.path.join(HERE, name), depth + 1):
                if not inner.lstrip().startswith('% Generated by'):   # notes for the source files only
                    out.append(inner)
            if out and not out[-1].endswith('\n'):
                out[-1] += '\n'
        else:
            out.append(line)
    return out


lines = expand(os.path.join(HERE, 'main.tex'))
text = ''.join(lines)
bib = '\\bibliographystyle{IEEEtran}\n\\bibliography{references}\n'
assert text.count(bib) == 1, 'main.tex should end with the IEEEtran bibliography commands'
text = text.replace(bib, '%% ---- bibliography (from %s) ----\n' % os.path.basename(BBL)
                    + open(BBL, encoding='utf-8').read())
head = ('% Which View Should Teach? Label-Aware Flip Consistency for Generalizable Polyp Segmentation.\n'
        '% The whole paper in one file, written by flatten.py from main.tex and the files it inputs.\n'
        '% Edit those sources, not this file. Build: pdflatex fct_paper.tex (twice).\n')
assert '\\input{' not in re.sub(r'(?m)^\s*%.*$', '', text), 'an \\input was left'
open(os.path.join(HERE, 'fct_paper.tex'), 'w', encoding='utf-8').write(head + text)
print('wrote fct_paper.tex: %d lines' % (head + text).count('\n'))
