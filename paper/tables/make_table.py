"""Build a main-results table (one per network) from seed_summary.py output.

It reads the last six-seed summary block "difference = <FCT> - <VANILLA>" in a seeds_*.out
file and writes a LaTeX table: rows are the test sets (seen, then unseen, then the mean),
columns are vanilla and FCT (mean +- SD), the paired gain, its 95% CI and the seeds better.
Gains whose CI excludes zero are bold. Numbers are copied, not recomputed.

Usage:
  python make_table.py SUMMARY_FILE VANILLA_ARM FCT_ARM "Network" "Backbone" LABEL OUT.tex [--first]
--first writes the full statistics note; later tables refer back to it.
"""
import re
import sys

SETS = [('Kvasir', 'Kvasir', 'seen'), ('ClinicDB', 'CVC-ClinicDB', 'seen'), ('ColonDB', 'CVC-ColonDB', 'unseen'),
        ('CVC-300', 'CVC-300', 'unseen'), ('ETIS', 'ETIS', 'unseen'), ('mean', 'Mean', 'mean')]
ROW = re.compile(r'^(\S+)\s+([\d.]+)\+-([\d.]+)\s+([\d.]+)\+-([\d.]+)\s+([+-][\d.]+)\s+\[\s*([+-][\d.]+),\s*([+-][\d.]+)\]'
                 r'\s+[\d.]+\s+[\d.]+\s+(\d)/6')


def read(path, van, fct):
    text = open(path, errors='replace').read()
    head = 'difference = %s - %s with the same seed' % (fct, van)
    i = text.rfind(head)
    if i < 0:
        sys.exit('no six-seed summary "%s" in %s' % (head, path))
    if 'seeds [1, 2, 3, 4, 5, 6]' not in text[max(0, i - 60):i]:
        sys.exit('the last summary for %s is not over seeds 1-6' % fct)
    rows = {}
    for line in text[i:].splitlines()[1:12]:
        m = ROW.match(line.strip())
        if m:
            rows[m.group(1)] = [float(x) for x in m.groups()[1:8]] + [int(m.group(9))]
    missing = [s for s, _, _ in SETS if s not in rows]
    if missing:
        sys.exit('summary rows missing: %s' % missing)
    return rows


def num(x, sign=False):
    """Dice points with a true minus sign; '+' only when asked."""
    v = 100 * x
    s = '%.2f' % abs(v)
    if v < 0:
        return '$-$' + s
    return ('+' + s) if sign else s


def row(name, r, indent=True):
    v, vsd, f, fsd, d, lo, hi, wins = r
    sig = lo > 0 or hi < 0
    b = (lambda s: '\\textbf{%s}' % s) if sig else (lambda s: s)
    cells = ['%s%s' % ('\\enspace ' if indent else '', name),
             num(v), num(vsd), num(f), num(fsd),
             b(num(d, sign=True)),
             b('[' + num(lo)), b(num(hi) + ']'),
             '%d/6' % wins]
    return ' & '.join(cells) + ' \\\\'


def main():
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    first = '--first' in sys.argv
    path, van, fct, net, backbone, label, out = args
    rows = read(path, van, fct)
    L = ['%% Generated by make_table.py from %s (%s vs %s); do not edit by hand.' % (path.split('/')[-1], fct, van),
         '\\begin{table}[t]', '\\centering', '\\footnotesize', '\\setlength{\\tabcolsep}{2.6pt}', '\\begin{threeparttable}',
         '\\caption{%s (%s) with and without FCT on five polyp test sets: mDice (\\%%), mean $\\pm$ SD over six seeds. '
         'Bold: gains whose 95\\%% CI excludes zero.}' % (net, backbone),
         '\\label{%s}' % label,
         '\\begin{tabular}{@{}l r@{$\\,\\pm\\,$}l r@{$\\,\\pm\\,$}l r r@{, }l c@{}}',
         '\\toprule',
         'Test set & \\multicolumn{2}{c}{Vanilla} & \\multicolumn{2}{c}{FCT (ours)} & Gain & \\multicolumn{2}{c}{95\\% CI} & Seeds \\\\',
         '\\midrule']
    for group, title in [('seen', 'Seen'), ('unseen', 'Unseen')]:
        L.append('\\multicolumn{9}{@{}l}{\\textit{%s}} \\\\' % title)
        for key, name, g in SETS:
            if g == group:
                L.append(row(name, rows[key]))
        if group == 'seen':
            L.append('\\addlinespace[2pt]')
    L.append('\\midrule')
    L.append(row(SETS[-1][1], rows['mean'], indent=False))
    L.append('\\bottomrule')
    L.append('\\end{tabular}')
    L.append('\\begin{tablenotes}[flushleft]')
    L.append('\\footnotesize')
    if first:
        L.append('\\item Training set: 1,288 Kvasir and \\mbox{CVC-ClinicDB} images; \\textit{seen}: test splits of the two '
                 'training datasets; \\textit{unseen}: datasets not used in training. Gain: mean paired difference, FCT minus vanilla '
                 'with the same seed. 95\\% CI: $t$-distribution, five degrees of freedom. Seeds: seeds, of six, on which '
                 'FCT scores higher. Mean: average over the five test sets.')
    else:
        L.append('\\item Columns and statistics as in Table~\\ref{tab:main_polyppvt}.')
    L += ['\\end{tablenotes}', '\\end{threeparttable}', '\\end{table}']
    open(out, 'w').write('\n'.join(L) + '\n')
    print('wrote', out, '| mean gain %+.2f [%.2f, %.2f], %d/6 seeds' % (100 * rows['mean'][4], 100 * rows['mean'][5], 100 * rows['mean'][6], rows['mean'][7]))


if __name__ == '__main__':
    main()
