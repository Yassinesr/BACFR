def per_image(path, van_prefix, fct_prefix):
    """Full-precision per-image analysis from the per_image_compare.py CSV (one row per image and run):
    gain, failures per run (Dice < 0.1 for the mask at 0.5 of the normalized map), missed and
    false-positive area (fractions of the polyp area), gains of the ten best and worst images and of
    the rest, and the gain per quarter of polyp size."""
    import csv, numpy as np
    rows = list(csv.DictReader(open(path)))
    out = {}
    for name in ['Kvasir', 'ClinicDB', 'ColonDB', 'CVC-300', 'ETIS']:
        R = [r for r in rows if r['set'] == name]
        imgs = sorted({r['image'] for r in R})
        runs_v = sorted({r['run'] for r in R if r['run'].startswith(van_prefix)})
        runs_f = sorted({r['run'] for r in R if r['run'].startswith(fct_prefix)})
        assert len(runs_v) == 6 and len(runs_f) == 6, (name, runs_v, runs_f)
        idx = {(r['run'], r['image']): r for r in R}
        def M(runs, k):
            return np.array([[float(idx[(u, i)][k]) for i in imgs] for u in runs])
        mv, mf = M(runs_v, 'meandic'), M(runs_f, 'meandic')
        d = mf.mean(0) - mv.mean(0)
        o = np.argsort(d)
        area = np.array([float(idx[(runs_v[0], i)]['polyp_area']) for i in imgs])
        b = np.digitize(area, np.quantile(area, [0.25, 0.5, 0.75]))
        quart = [float(d[b == q].mean()) for q in range(4)]
        dv, df = M(runs_v, 'dice05'), M(runs_f, 'dice05')
        out[name] = dict(gap=float(d.mean()), worst10=float(d[o[:10]].sum() / len(d)), best10=float(d[o[-10:]].sum() / len(d)),
                         fail=(float((dv < 0.1).sum(1).mean()), float((df < 0.1).sum(1).mean())),
                         fn=(float(M(runs_v, 'fn').mean()), float(M(runs_f, 'fn').mean())),
                         fp=(float(M(runs_v, 'fp').mean()), float(M(runs_f, 'fp').mean())),
                         small=quart[0], quarters=quart, n=len(imgs))
        out[name]['rest'] = out[name]['gap'] - out[name]['worst10'] - out[name]['best10']
    return out
