def drow(label, views, pulls, up, key, arm, step=None, gaparm=None, planned=6):
    """One row: components, gains over vanilla, the component effect against its reference row, sets,
    flip gap, cosine. A row trained with fewer than six seeds says so in its label."""
    n = NSEED.get(key, 6) if key in S else planned
    label = label + (' (%d seeds)' % n if key is not None and n < 6 else '')
    cells = [label, views, pulls, up]
    if key is None:                                       # vanilla
        cells += ['--', '--', '--', '--', num(G['PVT_VANILLA']['test_mean']), '--']
    elif key not in S:
        cells += [PEND('pending')] * 2 + [PEND('pending') if step else '--'] + [PEND('--')] * 3
    else:
        st_ = S[key]
        stepc = ci(DS[step]['mean']) if step in DS else (PEND('pending') if step else '--')
        g = G.get(gaparm) if gaparm else None
        cells += [ci(st_['mean']), ci(st_['ETIS']), stepc, '%d/5' % sets_up(st_),
                  num(g['test_mean']) if g else PEND('--'),
                  ('%.2f' % cos[arm]) if arm in cos else ('--' if pulls == NO else PEND('--'))]
    return ' & '.join(cells) + ' \\\\'


