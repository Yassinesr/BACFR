def pts(x, sign=False, nd=2):
    """Dice fraction -> points, with a true minus sign."""
    v = 100 * x
    s = ('%.' + str(nd) + 'f') % abs(v)
    if v < 0 and float(s) != 0:
        return '$-$' + s
    return ('+' + s) if sign else s


def num(v, nd=1, sign=False):
    s = ('%.' + str(nd) + 'f') % abs(v)
    if v < 0 and float(s) != 0:
        return '$-$' + s
    return ('+' + s) if sign else s


def ci(d, bold=True):
    """gain [lo, hi] in points, bold when the interval excludes zero."""
    txt = '%s [%s, %s]' % (pts(d['diff'], True), pts(d['lo']), pts(d['hi']))
    return '\\textbf{%s}' % txt if bold and (d['lo'] > 0 or d['hi'] < 0) else txt


