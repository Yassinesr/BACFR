# ------------------------------------------------------------------ cost: training time per epoch, without evaluation
LINE = re.compile(r'^(\d{4}-\d\d-\d\d \d\d:\d\d:\d\d(?:\.\d+)?) Epoch \[(\d+)/(\d+)\], Step \[(\d+)/(\d+)\]')
def train_min_per_epoch(arm, seed):
    """Median over epochs of the time between an epoch's first and last logged step, scaled to the epoch."""
    per = {}
    for line in open(os.path.join(REPO, 'logs_%s_s%d.txt' % (arm, seed)), errors='replace'):
        m = LINE.match(line.strip())
        if m:
            per.setdefault(int(m.group(2)), []).append((dt.datetime.fromisoformat(m.group(1)), int(m.group(4)), int(m.group(5))))
    rates = []
    for e, pts_ in per.items():
        if len(pts_) >= 2:
            (t0, s0, n), (t1, s1, _) = pts_[0], pts_[-1]
            if s1 > s0:
                rates.append((t1 - t0).total_seconds() / 60 * n / (s1 - s0))
    return st.median(rates)
